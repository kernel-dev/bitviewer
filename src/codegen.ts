// Code generation for a value's register fields: C header macros, a C
// bitfield struct, a Rust module and Python helpers.
import type { Group, ValueModel } from "./model";

export type Lang = "c" | "cstruct" | "rust" | "python";
export const LANG_NAMES: Record<Lang, string> = {
  c: "C macros",
  cstruct: "C struct",
  rust: "Rust",
  python: "Python",
};

export interface CodegenOptions {
  prefix: string; // e.g. "CTRL" — used for names
  includeValue: boolean; // emit the current value as a constant
}

/** UPPER_SNAKE identifier from free text ("Value 1" → "VALUE_1"). */
export function ident(s: string, fallback = "REG"): string {
  let id = s
    .trim()
    .replace(/[^A-Za-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .toUpperCase();
  if (!id) id = fallback;
  if (/^[0-9]/.test(id)) id = `_${id}`;
  return id;
}

const hex = (v: bigint) => `0x${v.toString(16).toUpperCase()}`;
const fieldMask = (g: Group) => ((1n << BigInt(g.width)) - 1n) << BigInt(g.lo);

/** Fields sorted from bit 0 upwards. */
const ascending = (m: ValueModel) => [...m.groups].sort((a, b) => a.lo - b.lo);

function comment(g: Group): string {
  const parts = [g.label()];
  if (g.access !== "rw") parts.push(g.access === "ro" ? "read-only" : "reserved");
  if (g.signed) parts.push("signed");
  if (g.formula) parts.push(`value = ${g.formula}${g.unit ? ` ${g.unit}` : ""}`);
  else if (g.unit) parts.push(g.unit);
  if (g.description) parts.push(g.description);
  return parts.join(" · ");
}

// ------------------------------------------------------------------ C macros
function cSuffix(width: number): string {
  return width <= 32 ? "U" : "ULL";
}

function genC(m: ValueModel, o: CodegenOptions): string {
  const P = ident(o.prefix);
  const out = [`/* ${m.name || P} — ${m.width}-bit register, generated by Bit Viewer */`, ""];
  if (m.width > 64) {
    out.push("/* C integer types stop at 64 bits; fields above bit 63 are listed as comments only. */", "");
  }
  const u = cSuffix(m.width);
  if (o.includeValue && m.width <= 64) out.push(`#define ${P}_VALUE ${hex(m.value)}${u}`, "");
  for (const g of ascending(m)) {
    const F = `${P}_${ident(g.name, "FIELD")}`;
    out.push(`/* ${g.name}: ${comment(g)} */`);
    if (g.hi > 63) {
      out.push(`/* ${F}: bits ${g.label()} — not representable in a C integer */`, "");
      continue;
    }
    out.push(
      `#define ${F}_POS   ${g.lo}U`,
      `#define ${F}_WIDTH ${g.width}U`,
      `#define ${F}_MASK  (${hex((1n << BigInt(g.width)) - 1n)}${u} << ${F}_POS)`,
      `#define ${F}_GET(reg)    (((reg) & ${F}_MASK) >> ${F}_POS)`,
      `#define ${F}_SET(reg, v) (((reg) & ~${F}_MASK) | (((v) << ${F}_POS) & ${F}_MASK))`,
    );
    for (const n of g.named) out.push(`#define ${F}_${ident(n.label, "VALUE")} ${hex(n.value)}${u}`);
    out.push("");
  }
  return `${out.join("\n").trimEnd()}\n`;
}

// ------------------------------------------------------------------ C struct
function genCStruct(m: ValueModel, o: CodegenOptions): string {
  const P = ident(o.prefix);
  if (m.width > 64) return `/* Bitfield structs need a value of 64 bits or less (this one has ${m.width}). */\n`;
  const store = m.width <= 8 ? 8 : m.width <= 16 ? 16 : m.width <= 32 ? 32 : 64;
  const t = `uint${store}_t`;
  const lines = [
    `/* ${m.name || P} — ${m.width}-bit register, generated by Bit Viewer.`,
    " * Bitfield order is implementation-defined; this assumes the first member",
    " * is the least significant bit (GCC, Clang and MSVC on little-endian targets). */",
    "#include <stdint.h>",
    "",
    "typedef union {",
    `  ${t} raw;`,
    "  struct {",
  ];
  let next = 0;
  const nameW = Math.max(4, ...m.groups.map((g) => ident(g.name, "FIELD").length));
  for (const g of ascending(m)) {
    if (g.lo > next)
      lines.push(
        `    ${t} ${"".padEnd(nameW)} : ${String(g.lo - next).padStart(2)};  /* [${g.lo - 1}:${next}] unused */`,
      );
    lines.push(
      `    ${t} ${ident(g.name, "FIELD").padEnd(nameW)} : ${String(g.width).padStart(2)};  /* ${comment(g)} */`,
    );
    next = g.hi + 1;
  }
  if (next < store) {
    lines.push(
      `    ${t} ${"".padEnd(nameW)} : ${String(store - next).padStart(2)};  /* [${store - 1}:${next}] unused */`,
    );
  }
  lines.push("  } bits;", `} ${P.toLowerCase()}_t;`);
  if (o.includeValue) lines.push("", `#define ${P}_VALUE ${hex(m.value)}${cSuffix(m.width)}`);
  return `${lines.join("\n")}\n`;
}

// ------------------------------------------------------------------ Rust
function genRust(m: ValueModel, o: CodegenOptions): string {
  const P = ident(o.prefix);
  if (m.width > 128) return `// Rust integers stop at 128 bits (this value has ${m.width}).\n`;
  const t = m.width <= 8 ? "u8" : m.width <= 16 ? "u16" : m.width <= 32 ? "u32" : m.width <= 64 ? "u64" : "u128";
  const out = [
    `/// ${m.name || P} — ${m.width}-bit register, generated by Bit Viewer.`,
    `pub mod ${P.toLowerCase()} {`,
  ];
  if (o.includeValue) out.push(`    pub const VALUE: ${t} = ${hex(m.value)};`, "");
  for (const g of ascending(m)) {
    const F = ident(g.name, "FIELD");
    const f = F.toLowerCase();
    out.push(
      `    /// ${g.name}: ${comment(g)}`,
      `    pub const ${F}_SHIFT: u32 = ${g.lo};`,
      `    pub const ${F}_MASK: ${t} = ${hex(fieldMask(g))};`,
      `    pub const fn ${f}(reg: ${t}) -> ${t} {`,
      `        (reg & ${F}_MASK) >> ${F}_SHIFT`,
      "    }",
      `    pub const fn set_${f}(reg: ${t}, v: ${t}) -> ${t} {`,
      `        (reg & !${F}_MASK) | ((v << ${F}_SHIFT) & ${F}_MASK)`,
      "    }",
    );
    for (const n of g.named) out.push(`    pub const ${F}_${ident(n.label, "VALUE")}: ${t} = ${hex(n.value)};`);
    out.push("");
  }
  if (out[out.length - 1] === "") out.pop();
  out.push("}");
  return `${out.join("\n")}\n`;
}

// ------------------------------------------------------------------ Python
function genPython(m: ValueModel, o: CodegenOptions): string {
  const P = ident(o.prefix);
  const out = [`"""${m.name || P} — ${m.width}-bit register, generated by Bit Viewer."""`, ""];
  if (o.includeValue) out.push(`${P}_VALUE = ${hex(m.value)}`, "");
  for (const g of ascending(m)) {
    const F = `${P}_${ident(g.name, "FIELD")}`;
    const f = F.toLowerCase();
    out.push(
      `# ${g.name}: ${comment(g)}`,
      `${F}_SHIFT = ${g.lo}`,
      `${F}_MASK = ${hex(fieldMask(g))}`,
      ...g.named.map((n) => `${F}_${ident(n.label, "VALUE")} = ${hex(n.value)}`),
      "",
      "",
      `def ${f}(reg):`,
      `    return (reg & ${F}_MASK) >> ${F}_SHIFT`,
      "",
      "",
      `def set_${f}(reg, value):`,
      `    return (reg & ~${F}_MASK) | ((value << ${F}_SHIFT) & ${F}_MASK)`,
      "",
      "",
    );
  }
  return `${out.join("\n").trimEnd()}\n`;
}

export function generate(lang: Lang, m: ValueModel, o: CodegenOptions): string {
  switch (lang) {
    case "c":
      return genC(m, o);
    case "cstruct":
      return genCStruct(m, o);
    case "rust":
      return genRust(m, o);
    case "python":
      return genPython(m, o);
  }
}

export const LANG_EXT: Record<Lang, string> = { c: "h", cstruct: "h", rust: "rs", python: "py" };
